#!/usr/bin/env python3
"""Measure the optional JIT against native PCRE2 and the saved original cohort.

Supply the native executable generated by run.py. Compilation, validation,
JIT benchmarking, and reference benchmarking run sequentially on one core.
"""
import argparse
import collections
import gzip
import hashlib
import io
import json
import math
import os
from pathlib import Path
import re
import statistics as stats
import subprocess
import shutil
import tarfile
import tempfile
import time

ROOT = Path(__file__).resolve().parents[2]
BASELINE = ROOT / "benchmarks/pcre2/results/2026-10-28-arm64"


def run(args, **kw):
    return subprocess.check_output([str(a) for a in args], text=True, **kw)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--cpu", type=int, default=min(os.sched_getaffinity(0)))
    parser.add_argument("--samples", type=int, default=7)
    parser.add_argument("--benchtime", default="20ms")
    parser.add_argument("--shared-process", action="store_true", help="run all JIT patterns in one process to measure context sensitivity")
    parser.add_argument("--nyanjit-ref", default="HEAD", help="committed sibling revision to isolate, plus the leaf-entry extension")
    args = parser.parse_args()
    os.sched_setaffinity(0, {args.cpu})
    env = dict(os.environ, GOWORK="off", GOMAXPROCS="1")
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    nyanjit_root = ROOT.parent / "nyanjit"
    nyanjit_head_at_build = run(["git", "rev-parse", args.nyanjit_ref], cwd=nyanjit_root).strip()
    frozen = Path(tempfile.mkdtemp(prefix="sources-", dir=out))
    frozen_root, frozen_nyanjit = frozen / "gopcre2", frozen / "nyanjit"
    frozen_root.mkdir()
    # Snapshot the implementation too, so independent development can continue
    # after the workers have been built without invalidating their identity.
    names = subprocess.check_output(["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"], cwd=ROOT).split(b"\0")
    for name in sorted(set(n for n in names if n)):
        source = ROOT / name.decode()
        if not source.is_file() or source.is_relative_to(out):
            continue
        if source.suffix not in {".go", ".s", ".mod", ".sum", ".gz"}:
            continue
        destination = frozen_root / name.decode()
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
    frozen_nyanjit.mkdir()
    archive = subprocess.check_output(["git", "archive", "--format=tar", nyanjit_head_at_build], cwd=nyanjit_root)
    with tarfile.open(fileobj=io.BytesIO(archive)) as tree:
        tree.extractall(frozen_nyanjit, filter="data")
    extension_files = ["backend/execution/leaf_func.go", "backend/execution/leaf_func_linux_test.go"]
    extension_hashes = {}
    for name in extension_files:
        source = nyanjit_root / name
        shutil.copyfile(source, frozen_nyanjit / name)
        extension_hashes[name] = hashlib.sha256(source.read_bytes()).hexdigest()
    modfile = frozen / "jit.mod"
    shutil.copyfile(frozen_root / "jit/go.mod", modfile)
    shutil.copyfile(frozen_root / "jit/go.sum", frozen / "jit.sum")
    for module, path in [("github.com/KarpelesLab/gopcre2", frozen_root),
                         ("github.com/moriyoshi/nyanjit", frozen_nyanjit),
                         ("github.com/moriyoshi/nyanjit/backend", frozen_nyanjit / "backend")]:
        run(["go", "mod", "edit", "-modfile="+str(modfile), "-replace="+module+"="+str(path)], cwd=frozen_root / "jit", env=env)
    def nyanjit_digest():
        digest = hashlib.sha256()
        for path in sorted(frozen_nyanjit.rglob("*")):
            if path.suffix not in {".go", ".s", ".mod", ".sum"}:
                continue
            digest.update(str(path.relative_to(frozen_nyanjit)).encode() + b"\0" + path.read_bytes() + b"\0")
        return digest.hexdigest()
    nyanjit_source_at_build = nyanjit_digest()
    corpus_bytes = gzip.decompress((BASELINE / "corpus.json.gz").read_bytes())
    cases = json.loads(corpus_bytes)
    (out / "corpus.json").write_bytes(corpus_bytes)
    original = {r["id"]: r for r in map(json.loads, gzip.decompress(
        (BASELINE / "results.jsonl.gz").read_bytes()).decode().splitlines())}
    run(["go", "build", "-o", out / "go-worker", "./benchmarks/pcre2/go"], cwd=frozen_root, env=env)
    run(["go", "test", "-modfile="+str(modfile), "-c", "-o", out / "jit-tests"], cwd=frozen_root / "jit", env=env)
    validation = run([out / "jit-tests", "-test.run", "TestPCRE2Corpus", "-test.v"], cwd=frozen_root / "jit", env=env)
    (out / "jit-validation.txt").write_text(validation)
    print(validation.strip(), flush=True)
    ids = re.search(r"Native case IDs: \[(.*?)\]", validation)
    if not ids:
        raise RuntimeError("Native validation did not enumerate its supported cases")
    native_ids = [int(i) for i in ids.group(1).split()]
    counts = collections.Counter()
    core = {}
    with (out / "core-validation.jsonl").open("w") as f:
        for case in cases:
            if case.get("skip") or case.get("rc", -2) < -1 or case.get("jit_error") or case.get("rc") != case.get("jit_rc"):
                continue
            try:
                r = json.loads(run([out / "go-worker", "-corpus", out / "corpus.json", "-id", case["id"]], timeout=3, env=env))
                status = "panic" if "panic" in r else "compile_error" if "compile_error" in r else "equal" if r.get("equal") else "mismatch"
            except subprocess.TimeoutExpired:
                r, status = {"id": case["id"]}, "timeout"
            r["status"] = status
            core[case["id"]] = r
            counts[status] += 1
            f.write(json.dumps(r) + "\n")
    regressions = [i for i, r in core.items() if original[i]["status"] == "measured" and r["status"] != "equal"]
    if regressions:
        raise RuntimeError(f"Original matching cohort regressed: {regressions}")
    print(f"Interpreter validation: {dict(counts)}", flush=True)
    command = [str(out / "jit-tests"), "-test.run", "^$", "-test.bench", "^BenchmarkPCRE2Corpus$",
               "-test.benchmem", "-test.benchtime=" + args.benchtime, "-test.count=" + str(args.samples)]
    samples = collections.defaultdict(lambda: collections.defaultdict(list))
    pattern = re.compile(r"^BenchmarkPCRE2Corpus/(\d+)/(reuse|api|call)(?:-\d+)?\s+\d+\s+([\d.]+) ns/op\s+(\d+) B/op\s+(\d+) allocs/op")
    seen = set()
    with (out / "jit-bench.txt").open("w") as f:
        commands = [command] if args.shared_process else [command + ["-pcre2-bench-case="+str(i)] for i in native_ids]
        for worker in commands:
            process = subprocess.Popen(worker, cwd=frozen_root / "jit", env=env, text=True, stdout=subprocess.PIPE)
            for line in process.stdout:
                f.write(line)
                match = pattern.match(line)
                if match:
                    i, mode, ns, byte, alloc = match.groups()
                    samples[int(i)][mode].append({"ns": float(ns), "bytes": int(byte), "allocs": int(alloc)})
                    if (i, mode) not in seen:
                        seen.add((i, mode))
                        if len(seen) % 50 == 0:
                            print(f"Measured {len(seen)} case/mode combinations", flush=True)
            if process.wait() != 0:
                raise RuntimeError("JIT benchmark failed; see jit-bench.txt")
    if set(samples) != set(native_ids):
        raise RuntimeError("Benchmark cases differ from validated native cases")
    combined = []
    with (out / "comparison.jsonl").open("w") as f:
        for i, modes in sorted(samples.items()):
            assert len(modes["reuse"]) == len(modes["api"]) == len(modes["call"]) == args.samples
            native = json.loads(run([args.native.resolve(), i, args.samples, 3000000], env=env, timeout=10))
            assert native["pattern_hex"] == cases[i-1]["pattern_hex"]
            assert native["captures"] == cases[i-1]["captures"] == native["jit_captures"]
            row = {"id": i, "jit": dict(modes), "native": native}
            if original[i]["status"] == "measured":
                row["original_go"] = original[i]["go"]
            if core[i]["status"] == "equal":
                row["updated_go"] = json.loads(run([out / "go-worker", "-corpus", out / "corpus.json", "-id", i,
                    "-samples", args.samples, "-duration", "3ms"], env=env, timeout=10))
                assert row["updated_go"]["equal"]
            f.write(json.dumps(row) + "\n")
            f.flush()
            combined.append(row)
    median = stats.median
    def jit(r, mode):
        return median(s["ns"] for s in r["jit"][mode])
    def geometric(values):
        return math.exp(stats.mean(math.log(v) for v in values))
    old = [r for r in combined if "original_go" in r]
    summary = {
        "native_cases": len(combined), "interpreter_counts": dict(counts), "original_cohort_regressions": regressions,
        "original_comparable_cases": len(old),
        "median_jit_reuse_ns": median(jit(r,"reuse") for r in combined),
        "median_jit_api_ns": median(jit(r,"api") for r in combined),
        "median_jit_reuse_over_native": median(jit(r,"reuse")/median(r["native"]["jit_ns"]) for r in combined),
        "p90_jit_reuse_over_native": sorted(jit(r,"reuse")/median(r["native"]["jit_ns"]) for r in combined)[math.ceil(.9*len(combined))-1],
        "geomean_jit_api_over_native_general": geometric(jit(r,"api")/median(r["native"]["jit_api_ns"]) for r in combined),
        "geomean_jit_api_over_native": geometric(jit(r,"api")/median(r["native"]["jit_ns"]) for r in combined),
        "geomean_jit_reuse_over_native": geometric(jit(r,"reuse")/median(r["native"]["jit_ns"]) for r in combined),
        "geomean_call_gateway_over_leaf": geometric(jit(r,"call")/jit(r,"reuse") for r in combined),
        "geomean_original_over_jit_api": geometric(median(r["original_go"]["ns"])/jit(r,"api") for r in old),
        "geomean_original_over_native_same_cohort": geometric(median(r["original_go"]["ns"])/median(r["native"]["jit_ns"]) for r in old),
        "geomean_jit_api_over_native_same_cohort": geometric(jit(r,"api")/median(r["native"]["jit_ns"]) for r in old),
        "all_reuse_samples_allocation_free": all(s["bytes"] == s["allocs"] == 0 for r in combined for s in r["jit"]["reuse"]),
    }
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    digest = hashlib.sha256()
    sources = sorted(frozen_root.glob("*.go")) + sorted((frozen_root/"jit").glob("*.go")) + [frozen_root/"jit/go.mod", frozen_root/"jit/go.sum"]
    for source in sources:
        digest.update(str(source.relative_to(frozen_root)).encode() + b"\0" + source.read_bytes() + b"\0")
    metadata = {"timestamp": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "cpu": args.cpu,
                "go": run(["go","version"]).strip(), "samples": args.samples,
                "jit_process_mode": "shared" if args.shared_process else "per-case", "jit_sample_target": args.benchtime,
                "native_sample_target": "3ms", "implementation_sha256": digest.hexdigest(),
                "corpus_sha256": hashlib.sha256(corpus_bytes).hexdigest(),
                "encoding_fixture_sha256": hashlib.sha256((frozen_root/"testdata/encoding.json.gz").read_bytes()).hexdigest(),
                "native_executable_sha256": hashlib.sha256(args.native.read_bytes()).hexdigest(),
                "nyanjit_head_at_build": nyanjit_head_at_build,
                "nyanjit_head": nyanjit_head_at_build,
                "nyanjit_live_head_at_finish": run(["git","rev-parse","HEAD"],cwd=nyanjit_root).strip(),
                "nyanjit_source_mode": "committed snapshot plus named leaf-entry extension files",
                "nyanjit_source_sha256": nyanjit_source_at_build,
                "nyanjit_extension_sha256": extension_hashes,
                "source_snapshot": str(frozen), "module_file": str(modfile),
                "nyanjit_live_dirty": bool(run(["git","status","--porcelain"],cwd=nyanjit_root).strip())}
    if nyanjit_digest() != nyanjit_source_at_build:
        raise RuntimeError("nyanjit source changed while measurements were running; rerun against a stable checkout")
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    print(json.dumps(summary, indent=2), flush=True)


if __name__ == "__main__":
    main()
